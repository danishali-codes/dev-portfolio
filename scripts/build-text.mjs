// Turns the wording in content/text/*.yaml into src/generated/text.ts.
//
// Each file is a namespace: `fortunes` in eggs.yaml becomes the key `eggs.fortunes`.
//
// src/text/schema.json is the contract with the code: every key the code reads, whether
// it's a line or a list, and the {placeholders} the code fills in. The YAML is checked
// against it, so a missing key or a made-up placeholder stops the build with a message
// that names the line, and the live site keeps the last good version.
//
// After adding or renaming keys in the code, run `npm run text:schema` to update the contract.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseDocument } from 'yaml'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const DIR = join(ROOT, 'content/text')
const OUT = join(ROOT, 'src/generated/text.ts')
const SCHEMA = join(ROOT, 'src/text/schema.json')
const WRITE_SCHEMA = process.argv.includes('--schema')

/** `{name}` or `{count|one|many}`. */
const PLACEHOLDER = /\{([A-Za-z_]\w*)(?:\|[^{}]*)?\}/g

const problems = []
const text = {}

function flatten(file, value, key) {
  if (typeof value === 'number' || typeof value === 'boolean') value = String(value)
  if (typeof value === 'string') return void (text[key] = value)
  if (value == null) return void problems.push(`${file}: "${key}" is empty. Write something after the colon, or put it in quotes: ''`)
  if (Array.isArray(value)) {
    const items = value.map((v) => (typeof v === 'number' || typeof v === 'boolean' ? String(v) : v))
    const bad = items.findIndex((v) => typeof v !== 'string')
    if (bad >= 0) return void problems.push(`${file}: item ${bad + 1} of "${key}" should be plain text (try putting it in quotes)`)
    if (!items.length) return void problems.push(`${file}: "${key}" is an empty list. It needs at least one line.`)
    return void (text[key] = items)
  }
  for (const [k, v] of Object.entries(value)) flatten(file, v, `${key}.${k}`)
}

const files = readdirSync(DIR).filter((f) => /\.ya?ml$/.test(f)).sort()
for (const file of files) {
  const doc = parseDocument(readFileSync(join(DIR, file), 'utf8'), { prettyErrors: true, uniqueKeys: true })
  if (doc.errors.length) {
    for (const e of doc.errors) problems.push(`${file}: ${e.message}`)
    continue
  }
  const data = doc.toJS()
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    problems.push(`${file}: should be a list of "key: text" lines`)
    continue
  }
  flatten(file, data, file.replace(/\.ya?ml$/, ''))
}

const placeholders = (v) => [...new Set([v].flat().flatMap((s) => [...s.matchAll(PLACEHOLDER)].map((m) => m[1])))].sort()
const where = (key) => {
  const [file, ...rest] = key.split('.')
  return `${file}.yaml, "${rest.join('.')}"`
}

if (!problems.length && WRITE_SCHEMA) {
  const schema = Object.fromEntries(Object.keys(text).sort().map((k) => [k, { list: Array.isArray(text[k]), vars: placeholders(text[k]) }]))
  writeFileSync(SCHEMA, JSON.stringify(schema, null, 2) + '\n')
  console.log(`text: wrote the contract for ${Object.keys(schema).length} keys to src/text/schema.json`)
}

const schema = JSON.parse(readFileSync(SCHEMA, 'utf8'))
if (!problems.length) {
  for (const [key, want] of Object.entries(schema)) {
    if (!(key in text)) {
      problems.push(`${where(key)} is missing. The site needs it, so put it back (it can say anything).`)
      continue
    }
    if (want.list && !Array.isArray(text[key])) problems.push(`${where(key)} should be a list (lines starting with "- ").`)
    if (!want.list && Array.isArray(text[key])) problems.push(`${where(key)} should be one line of text, not a list.`)
    const extra = placeholders(text[key]).filter((p) => !want.vars.includes(p))
    if (extra.length) {
      const can = want.vars.length ? `It can use ${want.vars.map((v) => `{${v}}`).join(', ')}.` : 'It has no placeholders.'
      problems.push(`${where(key)} uses ${extra.map((v) => `{${v}}`).join(', ')}, which the site doesn't fill in. ${can}`)
    }
  }
  for (const key of Object.keys(text)) if (!(key in schema)) console.warn(`text: ${where(key)} isn't used anywhere on the site yet.`)
}

if (problems.length) {
  console.error('\ncontent/text has a problem, so the site text was not rebuilt:\n')
  for (const p of problems) console.error('  • ' + p)
  console.error('')
  process.exit(1)
}

// Only keys the code knows about go into the build, typed by the contract rather than by the YAML.
const union = (names) => (names.length ? names.map((n) => `'${n}'`).join(' | ') : 'never')
const keys = Object.keys(schema).sort()
const strings = keys.filter((k) => !schema[k].list)
const lists = keys.filter((k) => schema[k].list)
const used = Object.fromEntries(keys.map((k) => [k, text[k]]))

const out = `// Generated by scripts/build-text.mjs from content/text/*.yaml. Do not edit.
export const TEXT: Record<string, string | readonly string[]> = ${JSON.stringify(used, null, 2)}

/** Every single-line key, with the placeholders its text uses. */
export interface Strings {
${strings.map((k) => `  '${k}': ${union(schema[k].vars)}`).join('\n')}
}

/** Every list key, with the placeholders any of its lines use. */
export interface Lists {
${lists.map((k) => `  '${k}': ${union(schema[k].vars)}`).join('\n')}
}
`
mkdirSync(join(OUT, '..'), { recursive: true })
writeFileSync(OUT, out)
// The server's messages on their own, so the API functions don't bundle the whole site's text.
const serverKeys = strings.filter((k) => k.startsWith('server.'))
writeFileSync(
  join(OUT, '../server-text.ts'),
  `// Generated by scripts/build-text.mjs from content/text/server.yaml. Do not edit.
const TEXT: Record<string, string> = ${JSON.stringify(Object.fromEntries(serverKeys.map((k) => [k, used[k]])), null, 2)}

export type ServerKey = ${serverKeys.map((k) => `'${k}'`).join(' | ') || 'never'}

/** A server message, with {placeholders} filled in. */
export function st(key: ServerKey, vars: Record<string, string | number> = {}): string {
  return (TEXT[key] ?? key).replace(/\\{(\\w+)\\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
`,
)

// The same text for build scripts (page titles, link previews) that can't import TypeScript.
writeFileSync(OUT.replace(/\.ts$/, '.json'), JSON.stringify(used, null, 2) + '\n')
console.log(`text: ${strings.length} lines and ${lists.length} lists from ${files.length} files`)
