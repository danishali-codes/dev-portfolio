// Compact notes for /api/ask, from the public content. cv.md is left out: it is
// still a draft, and the commented guesses in it are not facts. The caps are only a
// guard against a runaway file: today all of content/ (about 23k chars) fits whole.
//
// The README of every repo named by a project.json ("repo": "owner/name") is added
// too, so that list is the one place a repo gets approved: it shows on the site and
// Ask Danish knows about it. A README that can't be fetched is skipped, not fatal.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const CONTENT = join(ROOT, 'content')
const OUT = join(ROOT, 'api/_generated/context.ts')
const CAP = 120_000
const README_CAP = 25_000

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith('.')) continue
    const path = join(dir, name)
    if (statSync(path).isDirectory()) {
      if (name === 'trash' || name === 'text') continue
      walk(path, out)
    } else if (/\.(md|json)$/.test(name) && name !== 'cv.md') out.push(path)
  }
  return out
}

const clean = (text) =>
  text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/[^.]*\bhomelab\b[^.]*\.?/gi, '')
    .replace(/\s+/g, ' ')
    .trim()

const files = walk(CONTENT)
const parts = files.map((path) => {
  const rel = path.slice(CONTENT.length + 1)
  const text = clean(readFileSync(path, 'utf8')).slice(0, 8000)
  return text ? `## ${rel}\n${text}` : ''
})

// Strip what a model can't use from a README: code blocks, images, badges and HTML tags.
const prose = (md) =>
  md
    .replace(/```[\s\S]*?```/g, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/<[^>]+>/g, '')

async function fetchReadme(repo) {
  const tries = [
    [`https://api.github.com/repos/${repo}/readme`, {
      Accept: 'application/vnd.github.raw',
      'User-Agent': 'dev-portfolio-build',
      ...(process.env.GITHUB_TOKEN ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}),
    }],
    [`https://cdn.jsdelivr.net/gh/${repo}@HEAD/README.md`, {}],
  ]
  for (const [url, headers] of tries) {
    try {
      const res = await fetch(url, { headers, signal: AbortSignal.timeout(10_000) })
      if (res.ok) return await res.text()
    } catch {
      // try the next source
    }
  }
  return null
}

const repos = [...new Set(
  files
    .filter((path) => path.endsWith('project.json'))
    .map((path) => JSON.parse(readFileSync(path, 'utf8')).repo)
    .filter((repo) => typeof repo === 'string' && /^[\w.-]+\/[\w.-]+$/.test(repo)),
)]
for (const repo of repos) {
  const readme = await fetchReadme(repo)
  if (!readme) {
    console.warn(`ask: skipped README for ${repo} (fetch failed)`)
    continue
  }
  const text = clean(prose(readme)).slice(0, README_CAP)
  if (text) parts.push(`## github.com/${repo} README\n${text}`)
}

const body = parts.filter(Boolean).join('\n\n').slice(0, CAP)
mkdirSync(join(OUT, '..'), { recursive: true })
writeFileSync(OUT, `// Generated by scripts/build-ask.mjs. Do not edit.\nexport const ASK_CONTEXT = ${JSON.stringify(body)}\n`)
console.log(`ask: ${body.length} chars of notes -> api/_generated/context.ts`)
